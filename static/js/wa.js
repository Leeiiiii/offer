function readSavedLanguage() {
  try { return window.localStorage.getItem("preferredLanguage"); }
  catch (error) { return null; }
}

function saveLanguage(language) {
  try { window.localStorage.setItem("preferredLanguage", language); }
  catch (error) { /* Language switching still works without persistence. */ }
}

function applyLanguage(language, remember) {
  var locale = translations[language] ? language : "en";
  var strings = translations[locale];
  document.documentElement.lang = locale;
  document.title = strings.pageTitle;
  document.querySelectorAll("[data-i18n]").forEach(function (element) { element.textContent = strings[element.dataset.i18n]; });
  document.querySelectorAll("[data-i18n-html]").forEach(function (element) { element.innerHTML = strings[element.dataset.i18nHtml]; });
  document.querySelectorAll("[data-i18n-alt]").forEach(function (element) { element.alt = strings[element.dataset.i18nAlt]; });
  document.querySelectorAll("[data-i18n-aria]").forEach(function (element) { element.setAttribute("aria-label", strings[element.dataset.i18nAria]); });
  document.querySelectorAll("[data-i18n-content]").forEach(function (element) { element.setAttribute("content", strings[element.dataset.i18nContent]); });
  document.querySelectorAll("[data-language]").forEach(function (button) { button.setAttribute("aria-pressed", String(button.dataset.language === locale)); });
  if (remember) saveLanguage(locale);
}

document.querySelectorAll("[data-language]").forEach(function (button) { button.addEventListener("click", function () { applyLanguage(button.dataset.language, true); }); });

